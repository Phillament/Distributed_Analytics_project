"""Data Routing & Pre-processing Component (Edge Tier).

Paper, S3.2: "Its role is to forward data generated by Field sources to the
appropriate processor in the most efficient way, while hiding technical
complexities to both sides of the channel and also allowing for some basic
pre-processing of data -- e.g., filtering, in order to save network resources,
when the final destination of the information flow is in the Cloud.  As
opposed to Field Abstraction, this task is less concerned with time
constraints and more with data throughput."

Paper, S2.2: "Data routing refers to the capability of establishing direct
producer-consumer channels on demand, optimized for unidirectional massive
data streaming -- e.g., for feeding Analytics."

So this component provides:
  * `open_channel(...)` -- a direct producer-consumer channel created on
    demand, with a declared destination (EDGE or CLOUD);
  * a pre-processing pipeline of composable stages (dead band, decimation,
    window aggregation, threshold events);
  * byte accounting of what entered the channel versus what left it, which is
    the direct measurement of the paper's bandwidth-saving claim.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional

from ..common.messages import DataMessage, Event, StreamRecord

DEST_EDGE = "EDGE"      # consumer is local (Edge Analytics Engine)
DEST_CLOUD = "CLOUD"    # consumer is in the Cloud Tier -- filtering pays off

Stage = Callable[[StreamRecord], Optional[StreamRecord]]


# --------------------------------------------------------------------------
# Pre-processing stages
# --------------------------------------------------------------------------
class DeadBandFilter:
    """Drop readings that have not moved appreciably.

    The classic industrial filter: a sample that repeats the previous value
    within a relative tolerance carries no new information for automation, so
    it is dropped rather than forwarded.
    """

    name = "dead_band"

    def __init__(self, fraction: float = 0.02):
        self.fraction = fraction
        self._last: Dict[str, float] = {}
        self.dropped = 0
        self.passed = 0

    def __call__(self, rec: StreamRecord) -> Optional[StreamRecord]:
        kept: Dict[str, float] = {}
        for signal, value in rec.values.items():
            previous = self._last.get(signal)
            band = abs(previous) * self.fraction if previous is not None else 0.0
            if previous is None or abs(value - previous) > max(band, 1e-12):
                kept[signal] = value
                self._last[signal] = value
        if not kept:
            self.dropped += 1
            return None
        self.passed += 1
        return StreamRecord(source=rec.source, channel=rec.channel, values=kept,
                            t=rec.t, seq=rec.seq)


class Decimator:
    """Forward every n-th record (rate reduction)."""

    name = "decimate"

    def __init__(self, factor: int = 10):
        self.factor = max(1, factor)
        self._count = 0
        self.dropped = 0
        self.passed = 0

    def __call__(self, rec: StreamRecord) -> Optional[StreamRecord]:
        self._count += 1
        if self._count % self.factor:
            self.dropped += 1
            return None
        self.passed += 1
        return rec


class WindowAggregator:
    """Replace a window of records by its summary statistics."""

    name = "window_aggregate"

    def __init__(self, window: int = 50):
        self.window = max(1, window)
        self._buffer: List[StreamRecord] = []
        self.dropped = 0
        self.passed = 0

    def __call__(self, rec: StreamRecord) -> Optional[StreamRecord]:
        self._buffer.append(rec)
        if len(self._buffer) < self.window:
            self.dropped += 1
            return None
        signals = sorted({k for r in self._buffer for k in r.values})
        summary: Dict[str, float] = {}
        for signal in signals:
            series = [r.values[signal] for r in self._buffer if signal in r.values]
            if not series:
                continue
            summary[f"{signal}__mean"] = sum(series) / len(series)
            summary[f"{signal}__max"] = max(series)
            summary[f"{signal}__min"] = min(series)
        out = StreamRecord(source=rec.source, channel=f"{rec.channel}:agg",
                           values=summary, t=rec.t, seq=rec.seq)
        self._buffer.clear()
        self.passed += 1
        return out


class ThresholdDetector:
    """Emit an Event when a signal leaves its band -- the only thing that
    needs to travel with low latency."""

    name = "threshold"

    def __init__(self, limits: Dict[str, float],
                 sink: Optional[Callable[[Event], None]] = None):
        self.limits = limits
        self.sink = sink
        self.events = 0

    def __call__(self, rec: StreamRecord) -> Optional[StreamRecord]:
        for signal, limit in self.limits.items():
            value = rec.values.get(signal)
            if value is not None and value > limit:
                self.events += 1
                if self.sink:
                    self.sink(Event(source=rec.source, name="ThresholdExceeded",
                                    severity="WARN",
                                    payload={"signal": signal, "value": value,
                                             "limit": limit}, t=rec.t))
        return rec


