@dataclass
class ChannelStats:
    records_in: int = 0
    records_out: int = 0
    bytes_in: int = 0
    bytes_out: int = 0

    @property
    def reduction(self) -> float:
        return 1.0 - (self.bytes_out / self.bytes_in) if self.bytes_in else 0.0

    def as_dict(self) -> Dict[str, Any]:
        return {"records_in": self.records_in, "records_out": self.records_out,
                "bytes_in": self.bytes_in, "bytes_out": self.bytes_out,
                "byte_reduction": round(self.reduction, 4)}


class Channel:
    """A direct producer-consumer channel with a pre-processing pipeline."""

    def __init__(self, channel_id: str, producer: str, consumer: str,
                 destination: str, stages: List[Stage],
                 sink: Callable[[StreamRecord], None]):
        self.channel_id = channel_id
        self.producer = producer
        self.consumer = consumer
        self.destination = destination
        self.stages = stages
        self.sink = sink
        self.stats = ChannelStats()

    def push(self, rec: StreamRecord) -> Optional[StreamRecord]:
        self.stats.records_in += 1
        self.stats.bytes_in += rec.wire_size()
        current: Optional[StreamRecord] = rec
        for stage in self.stages:
            current = stage(current)
            if current is None:
                return None
        self.stats.records_out += 1
        self.stats.bytes_out += current.wire_size()
        self.sink(current)
        return current

    def describe(self) -> Dict[str, Any]:
        return {"channel_id": self.channel_id, "producer": self.producer,
                "consumer": self.consumer, "destination": self.destination,
                "pipeline": [getattr(s, "name", type(s).__name__) for s in self.stages],
                **self.stats.as_dict()}


class DataRouting:
    """The Component itself: creates and owns channels for one Gateway."""

    def __init__(self, gateway_id: str):
        self.gateway_id = gateway_id
        self.channels: Dict[str, Channel] = {}

    def open_channel(self, channel_id: str, producer: str, consumer: str,
                     sink: Callable[[StreamRecord], None],
                     destination: str = DEST_EDGE,
                     stages: Optional[List[Stage]] = None) -> Channel:
        channel = Channel(channel_id, producer, consumer, destination,
                          stages or [], sink)
        self.channels[channel_id] = channel
        return channel

    def close_channel(self, channel_id: str) -> None:
        self.channels.pop(channel_id, None)

    def route(self, channel_id: str, rec: StreamRecord) -> Optional[StreamRecord]:
        channel = self.channels.get(channel_id)
        if channel is None:
            raise KeyError(f"no channel {channel_id} on {self.gateway_id}")
        return channel.push(rec)

    # -- aggregate accounting --------------------------------------------
    def totals(self) -> Dict[str, Any]:
        bytes_in = sum(c.stats.bytes_in for c in self.channels.values())
        bytes_out = sum(c.stats.bytes_out for c in self.channels.values())
        return {"channels": len(self.channels),
                "records_in": sum(c.stats.records_in for c in self.channels.values()),
                "records_out": sum(c.stats.records_out for c in self.channels.values()),
                "bytes_in": bytes_in, "bytes_out": bytes_out,
                "byte_reduction": round(1.0 - bytes_out / bytes_in, 4) if bytes_in else 0.0}

    def stats(self) -> Dict[str, Any]:
        return {"totals": self.totals(),
                "channels": [c.describe() for c in self.channels.values()]}
